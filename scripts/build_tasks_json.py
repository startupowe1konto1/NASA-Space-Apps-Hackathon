"""Regenerate docs/tasks.json from docs/PLAN.md. Run from the repo root: python -I scripts/build_tasks_json.py

The plan is the source of truth. Never edit docs/tasks.json by hand; after a conflict, run this again.
"""
import io
import json
import re

PLAN = 'docs/PLAN.md'
OUT = 'docs/tasks.json'
SHARED = 'src/app/providers.ts'  # every provider swap is a [contract] PR to this file, merged one at a time

plan = io.open(PLAN, encoding='utf-8').read()

# 1. the task table: | ID | Owner | Stream | Task | After | Needed for minimum |
tasks = {}
for line in plan.splitlines():
    cells = [c.strip() for c in line.strip().strip('|').split('|')]
    if len(cells) == 6 and re.fullmatch(r'O\d-[A-Z]\d?', cells[0]):
        after = [] if cells[4] in ('–', '-', '') else re.findall(r'O\d-[A-Z]\d?', cells[4])
        tasks[cells[0]] = {
            'id': cells[0], 'owner': cells[1], 'stream': cells[2], 'title': cells[3],
            'after': after, 'minimum': cells[5] == 'yes', 'branch': None, 'files': [], 'conflicts': [],
        }

# 2. per-task text: from its heading (or its bullet for the short "after the minimum" tasks) to the next one
marks = [(m.start(), m.group(1)) for m in re.finditer(r'^(?:### |- \*\*)(O\d-[A-Z]\d?)[ :,]', plan, re.M)]
for i, (pos, task_id) in enumerate(marks):
    if task_id not in tasks:
        continue
    end = marks[i + 1][0] if i + 1 < len(marks) else len(plan)
    text = plan[pos:end]
    branch = re.search(r'`(o\d/[a-z0-9-]+)`', text)
    if branch:
        tasks[task_id]['branch'] = branch.group(1)
    files = re.search(r'\*\*Files:\*\*(.*)', text)
    if files:
        tasks[task_id]['files'] = re.findall(r'`([^`]+)`', files.group(1))
    if re.search(r'`\[contract\]` PR: (point|set) ', text):  # the steps that swap a provider or flip moneyAvailable
        tasks[task_id]['conflicts'].append(SHARED)

missing = [t for t, v in tasks.items() if v['branch'] is None and t != 'O1-R']
unknown = sorted({a for v in tasks.values() for a in v['after'] if a not in tasks})
if unknown:
    raise SystemExit(f'After refers to tasks that are not in the table: {unknown}')

out = {
    'generatedFrom': PLAN,
    'note': 'Generated by scripts/build_tasks_json.py. Do not edit by hand.',
    'tasks': list(tasks.values()),
}
io.open(OUT, 'w', encoding='utf-8', newline='\n').write(json.dumps(out, indent=2, ensure_ascii=False) + '\n')
print(f'{len(tasks)} tasks written to {OUT}; without a branch: {missing}')
